def canonical(value):return json.dumps(value,sort_keys=True,ensure_ascii=False,separators=(',',':'))
def digest(value):return hashlib.sha256(canonical(value).encode()).hexdigest()


def operation(value):
    key=value.get('operation_id');reason=value.get('reason')
    try:valid=isinstance(key,str) and str(uuid.UUID(key))==key
    except (ValueError,TypeError,AttributeError):valid=False
    if not valid:raise ValueError('Coupon operation identity')
    if not isinstance(reason,str) or not 2<=len(reason.strip())<=200:
        raise ValueError('Coupon operation reason bound')
    return key


def account_id(value):
    if type(value) is not int or not 2<=value<2**63:raise ValueError('Coupon account identity')
    return value


def reward_plan(rows):
    from els_server.domain.reward_rules import item_plan
    from els_server.storage.inventory_state import validate_plan
    from els_server.game_data import client_data
    if not isinstance(rows,list) or not 1<=len(rows)<=8:raise ValueError('Coupon reward line bound')
    result=[];seen=set();total=0
    for row in rows:
        if not isinstance(row,dict) or set(row)!={'template','quantity'}:raise ValueError('Coupon reward fields')
        template,quantity=row['template'],row['quantity']
        if (type(template) is not int or type(quantity) is not int or not 1<=quantity<=99
                or template in seen or template not in ELIGIBLE_REWARDS):
            raise ValueError('Coupon reward is outside the qualified ordinary set')
        native=client_data().item(template)
        if hashlib.sha256(native['record']).hexdigest()!=ELIGIBLE_REWARDS[template][0] or native['record'][210]!=ELIGIBLE_REWARDS[template][1]:
            raise ValueError('Coupon reward source changed')
        plan=item_plan(template,quantity)
        from els_server.domain.inventory_items import TEMPLATE_MAX_STACKS
        if plan['metadata']!=0 or plan['group']!=7 or TEMPLATE_MAX_STACKS[template]!=1:
            raise ValueError('Coupon ordinary source definition changed')
        validate_plan([plan]);seen.add(template);total+=quantity
        result.append(dict(plan,name=native['name'],record_sha256=ELIGIBLE_REWARDS[template][0],unit_type=ELIGIBLE_REWARDS[template][1],required_class=native['record'][211]))
    if total>99:raise ValueError('Coupon reward total bound')
    return result


def settings(value):
    if set(value)!={'operation_id','reason','count','max_redemptions','starts_at','expires_at','account_id','rewards'}:
        raise ValueError('Coupon issuance fields')
    operation(value)
    for name,upper in (('count',100),('max_redemptions',100)):
        if type(value[name]) is not int or not 1<=value[name]<=upper:raise ValueError('Coupon issuance count bound')
    for name in ('starts_at','expires_at'):
        if type(value[name]) is not int or not 0<=value[name]<2**63:raise ValueError('Coupon issuance time bound')
    bound=value['account_id']
    if bound is not None:
        account_id(bound)
        if value['max_redemptions']!=1:raise ValueError('Bound coupon has one redemption')
    return dict(count=value['count'],max_redemptions=value['max_redemptions'],starts_at=value['starts_at'],
                expires_at=value['expires_at'],account_id=bound,rewards=reward_plan(value['rewards']))


