def issue(path,value,*,validate=lambda bound:None,now=time.time):
    key=operation(value);request_digest=digest(['coupon-issue',value])
    # A committed immutable batch can be retrieved after later source policy
    # changes. No new entitlement is being admitted by that replay.
    with _reading(path)as db:
        if db is not None:
            old=_issuer_receipt(db,key,request_digest)
            if old is not None:return dict(old,replayed=True)
    policy=settings(value)
    with closing(_write(path))as db:
        try:
            db.execute('PRAGMA foreign_keys=ON');db.execute('BEGIN IMMEDIATE');initialize(db)
            old=_issuer_receipt(db,key,request_digest)
            if old is not None:db.commit();return dict(old,replayed=True)
            if db.execute('SELECT 1 FROM coupon_batches WHERE revoke_operation=?',(key,)).fetchone():raise ValueError('Conflicting coupon operation')
            moment=int(now());start=policy['starts_at'] or moment;end=policy['expires_at'];policy['starts_at']=start
            if not moment<=start<end<=moment+366*86400:raise ValueError('Coupon validity window')
            validate(policy['account_id'])
            if reward_plan(value['rewards'])!=policy['rewards']:raise ValueError('Coupon reward definition changed')
            db.execute('INSERT INTO coupon_batches(operation_id,digest,policy_json,reason,created_at)VALUES(?,?,?,?,?)',
                       (key,request_digest,canonical(policy),value['reason'],moment))
            first=_next(db,'coupon_products','product_no',len(policy['rewards']))
            for n,row in enumerate(policy['rewards']):db.execute('INSERT INTO coupon_products VALUES(?,?,?,?)',(first+n,key,n,canonical(row)))
            for n in range(policy['count']):
                for attempt in range(20):
                    serial=''.join(secrets.choice(string.ascii_uppercase)for _ in range(20));code_hash=hashlib.sha256(serial.encode('ascii')).hexdigest()
                    if not db.execute('SELECT 1 FROM coupon_codes WHERE code_hash=?',(code_hash,)).fetchone():break
                else:raise ValueError('Coupon entropy collision bound')
                db.execute('INSERT INTO coupon_codes VALUES(?,?,?,?,0)',(code_hash,serial,key,n))
            result=dict(_issuer_receipt(db,key),replayed=False)
            canonical(result)  # Check complete GM response before commit.
            db.commit();return result
        except BaseException:db.rollback();raise


def revoke(path,value,*,now=time.time):
    if set(value)!={'operation_id','reason','batch_id'}:raise ValueError('Coupon revocation fields')
    key=operation(value);request_digest=digest(['coupon-revoke',value]);batch=value['batch_id']
    with closing(_write(path))as db:
        try:
            db.execute('BEGIN IMMEDIATE')
            if not _present(db):raise ValueError('Coupon batch unavailable')
            old=db.execute('SELECT operation_id,revoke_digest FROM coupon_batches WHERE revoke_operation=?',(key,)).fetchone()
            if old:
                if old!=(batch,request_digest):raise ValueError('Conflicting coupon revocation retry')
                db.commit();return dict(_public(db,batch),replayed=True)
            if db.execute('SELECT 1 FROM coupon_batches WHERE operation_id=?',(key,)).fetchone():raise ValueError('Conflicting coupon operation')
            row=db.execute('SELECT revoked_at FROM coupon_batches WHERE operation_id=?',(batch,)).fetchone()
            if row is None:raise ValueError('Coupon batch unavailable')
            if row[0]is not None:
                # Preserve the first revocation UUID/digest. Another explicit
                # revocation is a no-op, never a rewrite of that decision.
                result=dict(_public(db,batch),replayed=True,already_revoked=True)
                db.commit();return result
            db.execute('UPDATE coupon_batches SET revoked_at=?,revoke_operation=?,revoke_digest=?,revoke_reason=? WHERE operation_id=?',
                       (int(now()),key,request_digest,value['reason'],batch))
            result=dict(_public(db,batch),replayed=False);canonical(result);db.commit();return result
        except BaseException:db.rollback();raise


def batches(path,offset=0):
    if type(offset)is not int or not 0<=offset<=100000:raise ValueError('Coupon batch page bound')
    with _reading(path)as db:
        if db is None:return dict(total=0,rows=[],offset=offset)
        ids=[r[0]for r in db.execute('SELECT operation_id FROM coupon_batches ORDER BY created_at DESC,operation_id LIMIT 20 OFFSET ?',(offset,))]
        return dict(total=db.execute('SELECT COUNT(*)FROM coupon_batches').fetchone()[0],rows=[_public(db,k)for k in ids],offset=offset)


def _owner(db,account,owner):
    account_id(account)
    if type(owner)is not int or not 1001<=owner<2**63:raise ValueError('Coupon role identity')
