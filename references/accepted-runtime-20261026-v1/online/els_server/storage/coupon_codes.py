def _present(db):return TABLES<={r[0]for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}


@contextmanager
def _reading(path):
    path=Path(path).resolve()
    if not path.is_file():yield None;return
    with closing(sqlite3.connect(path.as_uri()+'?mode=ro',uri=True,timeout=10))as db:
        db.execute('BEGIN')
        yield db if _present(db)else None


def _write(path):
    # Explicit mutations also require the configured existing save. A wrong
    # path must not silently create an empty player database.
    return sqlite3.connect(Path(path).resolve().as_uri()+'?mode=rw',uri=True,timeout=10)


def _next(db,table,column,count=1):
    if (table,column)not in(('coupon_products','product_no'),('cash_deposit_orders','trans_no')):
        raise ValueError('Coupon allocator domain')
    first=db.execute('SELECT COALESCE(MAX('+column+'),0)+1 FROM '+table).fetchone()[0]
    if not 1<=first<=first+count-1<2**31:raise ValueError('Coupon ledger identity exhausted')
    # Rows/tombstones are retained, never deleted, hence committed IDs are not
    # recycled. BEGINIMMEDIATE serializes this finite allocator without a new
    # cross-domain inventory sequence or sqlite_sequence table.
    return first


def _public(db,batch_id):
    row=db.execute('SELECT policy_json,reason,created_at,revoked_at,revoke_operation,revoke_reason FROM coupon_batches WHERE operation_id=?',(batch_id,)).fetchone()
    if row is None:return None
    return dict(operation_id=batch_id,policy=json.loads(row[0]),reason=row[1],created_at=row[2],revoked_at=row[3],revoke_operation=row[4],revoke_reason=row[5],
                codes=[dict(ordinal=r[0],code_hash=r[1],used=r[2])for r in db.execute(
                    'SELECT ordinal,code_hash,used FROM coupon_codes WHERE batch_id=? ORDER BY ordinal',(batch_id,))])


def _issuer_receipt(db,key,expected_digest=None):
    row=db.execute('SELECT digest FROM coupon_batches WHERE operation_id=?',(key,)).fetchone()
    if row is None:return None
    if expected_digest is not None and row[0]!=expected_digest:raise ValueError('Conflicting coupon issuer retry')
    result=_public(db,key)
    result['codes']=[r[0]for r in db.execute('SELECT serial_private FROM coupon_codes WHERE batch_id=? ORDER BY ordinal',(key,))]
    return result


def issuer_receipt(path,key):
    try:valid=isinstance(key,str) and str(uuid.UUID(key))==key
    except (ValueError,TypeError,AttributeError):valid=False
    if not valid:raise ValueError('Coupon operation identity')
    with _reading(path)as db:return _issuer_receipt(db,key)if db is not None else None


def issuer_operation(path,key,action):
    if action=='coupon-issue':return issuer_receipt(path,key)
    if action!='coupon-revoke':raise ValueError('Coupon operation kind')
    try:valid=isinstance(key,str)and str(uuid.UUID(key))==key
    except (ValueError,TypeError,AttributeError):valid=False
    if not valid:raise ValueError('Coupon operation identity')
    with _reading(path)as db:
        if db is None:return None
        row=db.execute('SELECT operation_id FROM coupon_batches WHERE revoke_operation=?',(key,)).fetchone()
        return dict(_public(db,row[0]),replayed=True)if row else None


